import { ROLES } from "./config.js";

export function createBasePromptByRole(user) {
  if (user.role === ROLES.ADMIN) {
    return `
Ты — квалифицированный повар, определяющий ингредиенты блюда по его названию.
Тебе дается название желаемого блюда и список продуктов, имеющихся в холодильнике.
Твоя задача — составить список недостающих продуктов, которые нужно купить.
Правила:
- возвращай только список продуктов, которые нужно докупить;
- не возвращай продукты, не имеющие отношения к блюду;
- не возвращай продукты, которые уже есть в холодильнике.
`;
  }

  if (user.role === ROLES.USER) {
    return `
Ты — квалифицированный повар, определяющий ингредиенты блюда по его названию.
Тебе дается название желаемого блюда и список продуктов, имеющихся в холодильнике.
Твоя задача — выбрать продукты из холодильника, которые можно использовать для приготовления блюда.
Правила:
- возвращай только продукты из числа имеющихся в холодильнике;
- не возвращай продукты, не имеющие отношения к блюду;
- не возвращай продукты, которых нет в холодильнике.
`;
  }

  if (user.role === ROLES.GUEST) {
    return `
Ты — квалифицированный повар.
Тебе дается название блюда и список продуктов, имеющихся в холодильнике.
Пользователь имеет роль GUEST.
Составь короткую рекомендацию: какие из имеющихся продуктов подходят для блюда и каких основных ингредиентов не хватает.
Не добавляй продукты, не относящиеся к этому блюду.
`;
  }

  throw new Error(`Access denied: ${user.role}`);
}

export function formatProductsForPrompt(products) {
  return products
    .map((product) => `${product.name}: ${product.count}`)
    .join("\n");
}

export function createPrompt(basePrompt, dishTitle, products) {
  if (!dishTitle.trim()) {
    throw new Error("Введите название блюда");
  }

  if (!Array.isArray(products)) {
    throw new Error("Products must be an array");
  }

  const productsText = formatProductsForPrompt(products);

  return `${basePrompt}\nЖелаемое блюдо: ${dishTitle}\nПродукты в холодильнике:\n${productsText}`;
}
